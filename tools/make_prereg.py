"""Build docs/prereg.md from spec 0001 sections 3 to 6, verbatim, plus the values fixed at lock."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs/specs/0001-cross-model-pollination.md"
OUT = ROOT / "docs/prereg.md"


def sections(text: str, keep: list[str]) -> str:
    parts = re.split(r"(?m)^## ", text)
    out = []
    for p in parts:
        head = p.split("\n", 1)[0]
        num = head.split(".", 1)[0].strip()
        if num in keep:
            out.append("## " + p.rstrip() + "\n")
    return "\n".join(out)


def main(values_path: str | None) -> None:
    spec = SPEC.read_text()
    values = json.loads(Path(values_path).read_text()) if values_path else {}
    lines = [
        "# Pre-registration: does cross-model pollination help open autoresearch?",
        "",
        "Author: Wisdom Okechukwu",
        "",
        "This file is generated by `tools/make_prereg.py` from spec 0001 sections 3 to 6, copied verbatim, and is locked by the tag `prereg-v1` together with the code and data checksums listed in section 5.8. Any later change is recorded in `docs/DEVIATIONS.md`.",
        "",
        "## Values fixed at lock",
        "",
    ]
    if values:
        for k in sorted(values):
            if k == "margin":
                lo, hi = values[k]
                lines.append(f"margin: [{lo:.2f}, {hi:.2f}]")
            else:
                lines.append(f"- {k}: {values[k]}")
    else:
        lines.append("- PENDING: snapshot freeze time, study benchmarks, power gate result, margin.")
    lines.append("")
    lines.append(sections(spec, ["3", "4", "5", "6"]))
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
