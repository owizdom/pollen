"""paper/numbers.tex: one \\newcommand per number, every value read from results/*.json."""
from __future__ import annotations

import json
import math
import re
from pathlib import Path

from analysis import study

_WORDS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def camel(s) -> str:
    """Letters-only CamelCase of a key; digits become words."""
    s = re.sub(r"\d", lambda m: " " + _WORDS[int(m.group())] + " ", str(s))
    return "".join(w.capitalize() for w in re.split(r"[^A-Za-z]+", s) if w)


def alpha(i) -> str:
    out = ""
    i += 1
    while i:
        i, r = divmod(i - 1, 26)
        out = chr(65 + r) + out
    return out


def f3(x) -> str:
    return f"{x:.3f}"


def esc(s) -> str:
    return str(s).replace("_", r"\_")


def _load(root, name):
    p = Path(root) / "results" / f"{name}.json"
    return json.loads(p.read_text()) if p.is_file() else {}


def collect(root) -> dict:
    conf, sec = _load(root, "confirmatory"), _load(root, "secondary")
    sens, expl = _load(root, "sensitivity"), _load(root, "exploratory")
    m = {}

    def num(name, v, fmt=f3):
        if v is not None and not (isinstance(v, float) and not math.isfinite(v)):
            m[name] = fmt(v)

    def orr(name, v):
        if v is not None:
            m[name] = f3(math.exp(v))

    p = conf.get("pooled")
    if p:
        num("PooledLogOR", p["log_or"])
        orr("PooledOR", p["log_or"])
        orr("PooledORLow", p["ci95"][0])
        orr("PooledORHigh", p["ci95"][1])
        orr("PooledORNinetyLow", p["ci90"][0])
        orr("PooledORNinetyHigh", p["ci90"][1])
        num("PooledTauSquared", p["tau2"])
        m["PooledK"] = str(p["k"])
    if conf:
        m["PooledVerdict"] = esc(conf["verdict"])
        num("MarginLow", conf["margin"][0], lambda v: f"{v:.2f}")
        num("MarginHigh", conf["margin"][1], lambda v: f"{v:.2f}")
        cs = conf["case_study"]
        m["CaseStudyVerdict"] = esc(cs["verdict"])
        if cs.get("benchmark"):
            m["CaseStudyBenchmark"] = esc(cs["benchmark"])
    letters = {}
    for i, name in enumerate(sorted(conf.get("benchmarks", {}))):
        letters[name] = alpha(i)
        b, L = conf["benchmarks"][name], alpha(i)
        m[f"Bench{L}Name"] = esc(b["name"])
        orr(f"Bench{L}OR", b["estimate"]["log_or"])
        num(f"Bench{L}LogOR", b["estimate"]["log_or"])
        m[f"Bench{L}AnalysisRows"] = str(b["counts"]["analysis_rows"])
        m[f"Bench{L}FitRows"] = str(b["counts"]["fit_rows"])
        m[f"Bench{L}StrataKept"] = str(b["counts"]["strata_kept"])
    for t in sec.get("tests", []):
        base = f"Sec{camel(t['hypothesis'])}{letters.get(t['benchmark'], camel(t['benchmark']))}"
        m[f"{base}Events"] = str(t["min_arm_events"])
        num(f"{base}P", t["p"])
        num(f"{base}PHolm", t["p_holm"])
    for k, v in sorted(sens.get("sensitivities", {}).items()):
        if "pooled" in v:
            base = f"Sens{camel(k)}"
            orr(f"{base}OR", v["pooled"]["log_or"])
            orr(f"{base}ORLow", v["pooled"]["ci95"][0])
            orr(f"{base}ORHigh", v["pooled"]["ci95"][1])
    for k, v in sorted(expl.get("E2", {}).get("pooled", {}).items()):
        if v:
            orr(f"ExploreE{camel(k)}OR", v["log_or"])
    return m


def write(root=None) -> Path:
    root = study.guard(root)
    macros = collect(root)
    lines = ["% Generated by analysis.numbers from results/*.json. Do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{macros[k]}}}" for k in sorted(macros)]
    out = Path(root) / "paper" / "numbers.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out
